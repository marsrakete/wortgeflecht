const catalogs = { de, en, fr };
const browserLanguages = globalThis.navigator?.languages ?? [];
const preferences = browserLanguages.length ? browserLanguages : [globalThis.navigator?.language ?? ""];
export const locale = preferences
  .map(language => language.toLowerCase().split("-")[0])
  .find(language => Object.hasOwn(catalogs, language)) ?? "de";
export const messages = catalogs[locale];
